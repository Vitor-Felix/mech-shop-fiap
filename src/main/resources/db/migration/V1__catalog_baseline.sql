CREATE TABLE IF NOT EXISTS customer_entity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS part_entity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    stock_quantity INTEGER NOT NULL,
    unit_price NUMERIC(38, 2) NOT NULL
);

CREATE TABLE IF NOT EXISTS work_entity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount NUMERIC(38, 2) NOT NULL,
    description VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS vehicle_entity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand VARCHAR(255) NOT NULL,
    color VARCHAR(255) NOT NULL,
    license_plate VARCHAR(255),
    model VARCHAR(255) NOT NULL,
    price NUMERIC(12, 2) NOT NULL,
    sync_error VARCHAR(120),
    sync_status VARCHAR(16) DEFAULT 'PENDING' NOT NULL,
    version BIGINT NOT NULL,
    vehicle_year INTEGER NOT NULL,
    customer_id BIGINT,
    CONSTRAINT fk_vehicle_customer
        FOREIGN KEY (customer_id) REFERENCES customer_entity (id)
);

CREATE TABLE IF NOT EXISTS work_order_entity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finished_at TIMESTAMP(6),
    observation VARCHAR(255),
    started_at TIMESTAMP(6),
    status VARCHAR(255) NOT NULL,
    total_amount NUMERIC(38, 2) NOT NULL,
    customer_id BIGINT NOT NULL,
    vehicle_id BIGINT NOT NULL,
    CONSTRAINT fk_work_order_customer
        FOREIGN KEY (customer_id) REFERENCES customer_entity (id),
    CONSTRAINT fk_work_order_vehicle
        FOREIGN KEY (vehicle_id) REFERENCES vehicle_entity (id)
);

CREATE TABLE IF NOT EXISTS work_order_part (
    work_order_id BIGINT NOT NULL,
    part_id BIGINT NOT NULL,
    PRIMARY KEY (work_order_id, part_id),
    CONSTRAINT fk_work_order_part_order
        FOREIGN KEY (work_order_id) REFERENCES work_order_entity (id),
    CONSTRAINT fk_work_order_part_part
        FOREIGN KEY (part_id) REFERENCES part_entity (id)
);

CREATE TABLE IF NOT EXISTS work_order_service (
    work_order_id BIGINT NOT NULL,
    service_id BIGINT NOT NULL,
    PRIMARY KEY (work_order_id, service_id),
    CONSTRAINT fk_work_order_service_order
        FOREIGN KEY (work_order_id) REFERENCES work_order_entity (id),
    CONSTRAINT fk_work_order_service_work
        FOREIGN KEY (service_id) REFERENCES work_entity (id)
);
